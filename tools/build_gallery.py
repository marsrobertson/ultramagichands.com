#!/usr/bin/env python3
"""Import your own photos into the static gallery.

Usage: python3 tools/build_gallery.py --source /path/to/your/photos
Optional gallery/captions.json maps source filenames to captions/alt text:
{"example.jpg": {"caption": "Massage in the garden", "alt": "Mars at work outdoors"}}
Original files are never modified; web copies have image metadata removed.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
EXTENSIONS = {'.jpg', '.jpeg', '.png', '.webp', '.avif'}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    args = parser.parse_args()
    source = args.source.expanduser().resolve()
    if not source.is_dir():
        parser.error('Source must be a folder containing your photos.')
    files = sorted(p for p in source.iterdir() if p.suffix.lower() in EXTENSIONS and p.is_file())
    if not files:
        parser.error('No supported photos found. Export HEIC images as JPEG first.')
    captions_path = ROOT / 'gallery/captions.json'
    captions = json.loads(captions_path.read_text()) if captions_path.exists() else {}
    destination = ROOT / 'gallery/photos'
    destination.mkdir(parents=True, exist_ok=True)
    entries = []
    for path in files:
        digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
        filename = digest + '.jpg'
        with Image.open(path) as original:
            image = ImageOps.exif_transpose(original).convert('RGB')
            image.thumbnail((2000, 2000), Image.Resampling.LANCZOS)
            # Fresh pixel image prevents source EXIF, GPS, and other metadata transfer.
            clean = Image.new('RGB', image.size)
            clean.paste(image)
            clean.save(destination / filename, 'JPEG', quality=88, optimize=True, progressive=True)
            details = captions.get(path.name, {})
            entries.append({'src': 'gallery/photos/' + filename, 'w': clean.width,
                            'h': clean.height, 'caption': details.get('caption', ''),
                            'alt': details.get('alt', details.get('caption', 'Photo from Mars’s gallery'))})
    (ROOT / 'gallery/photos.js').write_text('// Generated by tools/build_gallery.py.\nwindow.GALLERY_PHOTOS = ' + json.dumps(entries, ensure_ascii=False, indent=2) + ';\n')
    print(f'Imported {len(entries)} photos. Originals unchanged; web copies stripped of metadata.')

if __name__ == '__main__':
    main()
