#!/usr/bin/env python3
"""Index the existing screenshot collection without modifying the originals."""
import csv
import json
import struct
from pathlib import Path

root = Path(__file__).resolve().parent.parent
entries = []
with (root / 'reviews/reviews.csv').open(newline='') as source:
    for row in csv.DictReader(source):
        path = root / 'reviews' / row['image']
        with path.open('rb') as image:
            header = image.read(24)
        if header[:8] != b'\x89PNG\r\n\x1a\n':
            raise ValueError(f'Not a PNG: {path}')
        width, height = struct.unpack('>II', header[16:24])
        entries.append(dict(src=row['image'], w=width, h=height,
                            reviewer=row['reviewer'], link=row['link']))
(root / 'reviews/reviews.js').write_text(
    '// Generated by tools/index_reviews.py.\nwindow.REVIEWS = ' +
    json.dumps(entries, ensure_ascii=False, indent=2) + ';\n')
print(f'Indexed {len(entries)} review screenshots.')
