(function () {
  // WhatsApp links: add a pre-filled message from data-msg.
  document.querySelectorAll('.js-wa').forEach(function (a) {
    var msg = a.getAttribute('data-msg');
    if (msg) a.href = a.href.split('?')[0] + '?text=' + encodeURIComponent(msg);
    a.target = '_blank';
    a.rel = 'noopener';
  });

  // Nav background + floating button once past the hero.
  var nav = document.querySelector('.nav');
  var fab = document.querySelector('.fab');
  function onScroll() {
    var y = window.scrollY;
    nav.classList.toggle('scrolled', y > 40);
    fab.classList.toggle('show', y > window.innerHeight * 0.8);
  }
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();

  // Review screenshots (reviews/reviews.js is generated by tools/build_reviews.py).
  var reviews = window.REVIEWS || [];
  var collage = document.getElementById('collage');
  if (reviews.length) {
    if (window.REVIEWS_MAPS_URL) {
      document.querySelectorAll('.js-maps').forEach(function (a) { a.href = window.REVIEWS_MAPS_URL; });
    }
    reviews.forEach(function (r) {
      var fig = document.createElement('figure');
      var img = document.createElement('img');
      img.src = 'reviews/' + r.src;
      img.width = r.w;
      img.height = r.h;
      img.loading = 'lazy';
      img.alt = 'Google Maps review screenshot';
      fig.appendChild(img);
      collage.appendChild(fig);
    });
    collage.hidden = false;
    var quotes = document.getElementById('quotes');
    if (quotes) quotes.hidden = true;
  }

  // Lightbox.
  var lb = document.getElementById('lightbox');
  var lbImg = lb.querySelector('img');
  collage.addEventListener('click', function (e) {
    var img = e.target.closest('img');
    if (!img) return;
    lbImg.src = img.src;
    lb.hidden = false;
  });
  lb.addEventListener('click', function () { lb.hidden = true; lbImg.src = ''; });
  document.addEventListener('keydown', function (e) { if (e.key === 'Escape') lb.click(); });
})();
